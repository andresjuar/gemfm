-- gem.fm schema (Postgres / Supabase).
-- Paste this whole file into Supabase › SQL Editor › New query › Run.
-- It is safe to run more than once.

create table if not exists users (
  id          integer generated by default as identity primary key,
  name        text not null,
  handle      text not null unique,
  color       text not null default '#F29AD3',
  created_at  timestamptz not null default now()
);

-- status: 'approved' artists appear in Discover. 'pending' ones come from the
-- emerging-artist radar and wait for review on the Artists page.
create table if not exists artists (
  id            integer generated by default as identity primary key,
  name          text not null,
  genre         text not null default '',
  city          text not null default '',
  bio           text not null default '',
  spotify_url   text not null default '',
  image_url     text not null default '',
  deezer_id     bigint unique,
  external_fans integer,
  source        text not null default 'manual' check (source in ('manual', 'import', 'radar')),
  status        text not null default 'approved' check (status in ('approved', 'pending', 'rejected')),
  color         text not null default '#6D2FB0',
  created_at    timestamptz not null default now()
);
create index if not exists artists_status_idx on artists (status);

create table if not exists venues (
  id    integer generated by default as identity primary key,
  name  text not null,
  area  text not null default ''
);

create table if not exists gigs (
  id         integer generated by default as identity primary key,
  artist_id  integer not null references artists(id) on delete cascade,
  venue_id   integer not null references venues(id) on delete cascade,
  starts_at  timestamptz not null,
  price_mxn  integer not null default 0
);
create index if not exists gigs_starts_at_idx on gigs (starts_at);
create index if not exists gigs_artist_idx on gigs (artist_id);

create table if not exists swipes (
  user_id     integer not null references users(id) on delete cascade,
  artist_id   integer not null references artists(id) on delete cascade,
  liked       boolean not null,
  created_at  timestamptz not null default now(),
  primary key (user_id, artist_id)
);
create index if not exists swipes_artist_idx on swipes (artist_id);

create table if not exists checkins (
  user_id     integer not null references users(id) on delete cascade,
  gig_id      integer not null references gigs(id) on delete cascade,
  created_at  timestamptz not null default now(),
  primary key (user_id, gig_id)
);
create index if not exists checkins_gig_idx on checkins (gig_id);

create table if not exists follows (
  follower_id  integer not null references users(id) on delete cascade,
  followee_id  integer not null references users(id) on delete cascade,
  created_at   timestamptz not null default now(),
  primary key (follower_id, followee_id),
  check (follower_id <> followee_id)
);

create table if not exists recommendations (
  id          integer generated by default as identity primary key,
  user_id     integer not null references users(id) on delete cascade,
  artist_id   integer not null references artists(id) on delete cascade,
  note        text not null default '',
  created_at  timestamptz not null default now()
);

-- ---------- Taste tags ----------
-- The tags people pick when they sign in. An artist gets every tag whose
-- pattern matches their genre (case-insensitive regex), so "Indie folk" is
-- tagged indie + folk. Edit the patterns here to tune the matching.
create table if not exists tags (
  slug     text primary key,
  label    text not null,
  pattern  text not null,
  sort     integer not null default 0
);

